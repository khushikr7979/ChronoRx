prescriptions_router = APIRouter(prefix="/prescriptions", tags=["Prescription History"])

@prescriptions_router.get("/{review_id}/download")
@router.get("/{review_id}/download")
def download_prescription_pdf(
    review_id: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Secure download endpoint for Prescription PDF:
    - Enforces IDOR protection: Patients can only download their own prescription PDF
    - Validates prescription review existence
    - Logs audit event
    - Returns FileResponse
    """
    review = db.query(PrescriptionReview).filter(PrescriptionReview.review_id == review_id).first()
    if not review:
        raise HTTPException(status_code=404, detail=f"Prescription review '{review_id}' not found.")

    if current_user.role == "patient":
        if current_user.patient_id != review.patient_id:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Access forbidden: Patients may only download their own prescription PDF."
            )
        if not review.is_reviewed or review.status != "ACTIVE":
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Access forbidden: Unverified or inactive prescriptions cannot be downloaded."
            )

    pdf_filename = f"ChronoRx_{review.patient_id}_{review.review_id}.pdf"
    pdf_path = os.path.join(settings.GENERATED_REPORTS_DIR, pdf_filename)
    if not os.path.exists(pdf_path):
        if review.pdf_path and os.path.exists(review.pdf_path):
            pdf_path = review.pdf_path
        else:
            raise HTTPException(status_code=404, detail="Prescription PDF file not found on server.")

    log_audit_event(
        db,
        patient_id=review.patient_id,
        user_id=current_user.user_id,
        action="PRESCRIPTION_DOWNLOADED",
        details=f"Prescription PDF {pdf_filename} downloaded by {current_user.user_id} ({current_user.role})."
    )

    return FileResponse(
        path=pdf_path,
        filename=pdf_filename,
        media_type="application/pdf"
    )

@prescriptions_router.get("/{patient_id}", response_model=List[PrescriptionReviewResponse])
@router.get("/patient/{patient_id}", response_model=List[PrescriptionReviewResponse])
def get_patient_prescriptions(
    patient_id: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Retrieves all generated prescriptions for a given patient."""
    if current_user.role == "patient":
        if current_user.patient_id != patient_id:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Access forbidden: Patients may only access their own prescriptions."
            )
        reviews = db.query(PrescriptionReview).filter(
            PrescriptionReview.patient_id == patient_id,
            PrescriptionReview.is_reviewed == True,
            PrescriptionReview.status == "ACTIVE"
        ).order_by(PrescriptionReview.created_at.desc()).all()
        return reviews

    reviews = db.query(PrescriptionReview).filter(
        PrescriptionReview.patient_id == patient_id
    ).order_by(PrescriptionReview.created_at.desc()).all()
    return reviews

@prescriptions_router.post("/{prescription_id}/send", response_model=DeliveryResponse)
def send_prescription_by_id(
    prescription_id: str,
    phone: Optional[str] = None,
    channel: str = "whatsapp",
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Tier 3: Dispatches a specific prescription by review ID."""
    if current_user.role == "patient":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access forbidden: Patients cannot dispatch prescriptions."
        )
    review = db.query(PrescriptionReview).filter(PrescriptionReview.review_id == prescription_id).first()
    if not review:
        raise HTTPException(status_code=404, detail=f"Prescription {prescription_id} not found.")

    return deliver_prescription(
        DeliveryRequest(
            patient_id=review.patient_id,
            review_id=review.review_id,
            phone=phone,
            delivery_channel=channel
        ),
        db=db,
        current_user=current_user
    )

@prescriptions_router.patch("/{review_id}/archive", response_model=PrescriptionReviewResponse)
def archive_prescription_review(
    review_id: str,
    reason: str = Query(..., description="Mandatory clinical reason for archiving or voiding prescription"),
    target_status: str = Query("ARCHIVED", description="ARCHIVED, VOID, or INCORRECT"),
    db: Session = Depends(get_db),
    current_user: User = Depends(require_roles(["doctor", "admin"]))
):
    """
    Controlled Archive / Void for E-Prescriptions:
    - Preserves clinical record for auditability
    - Enforces RBAC (Doctor or Admin)
    - Records archive reason, timestamp, and user
    - Patient record and other prescriptions remain intact
    - Logs audit event: PRESCRIPTION_ARCHIVED / PRESCRIPTION_VOIDED
    """
    review = db.query(PrescriptionReview).filter(PrescriptionReview.review_id == review_id).first()
    if not review:
        raise HTTPException(status_code=404, detail=f"Prescription {review_id} not found.")

    status_val = target_status.upper() if target_status.upper() in ["ARCHIVED", "VOID", "INCORRECT"] else "ARCHIVED"
    review.status = status_val
    review.archived_at = datetime.datetime.utcnow()
    review.archived_by = current_user.user_id
    review.archive_reason = reason.strip()
    db.commit()
    db.refresh(review)

    action_name = "PRESCRIPTION_VOIDED" if status_val == "VOID" else "PRESCRIPTION_ARCHIVED"
    log_audit_event(
        db,
        patient_id=review.patient_id,
        user_id=current_user.user_id,
        action=action_name,
        details=f"Prescription {review_id} marked {status_val} by {current_user.user_id}. Reason: {reason}"
    )

    return review

